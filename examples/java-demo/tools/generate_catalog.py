#!/usr/bin/env python3
"""Generate Backstage library entities from Java Demo's resolved Maven dependency tree."""

import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

DEMO_DIR = Path(__file__).resolve().parent.parent
POM = DEMO_DIR / "pom.xml"
ROOT_COORDINATES = ("nl.kadaster.demo", "java-demo")
TREE_GOAL = "org.apache.maven.plugins:maven-dependency-plugin:3.8.1:tree"
DEPENDENCIES_FILE = "catalog-dependencies.yaml"
LIBRARIES_FILE = "catalog-libraries.yaml"
OWNER = "user:default/gerard-bloemendaal"
COMPONENT_PREFIX = "component:default/"
SCOPES = {"compile", "provided", "runtime", "system", "test"}
REQUIRED_KEYS = {"groupId", "artifactId", "version", "type", "scope", "classifier", "optional"}
TOKEN = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*")
MAX_NAME = 63
HASH_LENGTH = 12
HEADER = (
    "# Generated by examples/java-demo/tools/generate_catalog.py from Maven's resolved\n"
    "# dependency tree. Do not edit; regenerate it instead.\n"
)


class TreeError(ValueError):
    pass


def coordinate(identity):
    group, artifact, version, kind, classifier = identity
    if kind == "jar" and not classifier:
        return f"{group}:{artifact}:{version}"
    return ":".join(part for part in (group, artifact, kind, classifier, version) if part)


def entity_name(identity):
    digest = hashlib.sha256("\n".join(identity).encode()).hexdigest()[:HASH_LENGTH]
    slug = re.sub(r"[^a-z0-9]+", "-", identity[1].lower()).strip("-")
    slug = slug[: MAX_NAME - len("maven--") - HASH_LENGTH].rstrip("-")
    return "-".join(part for part in ("maven", slug, digest) if part)


def entity_ref(identity):
    return COMPONENT_PREFIX + entity_name(identity)


def _identity(node, path):
    if not isinstance(node, dict):
        raise TreeError(f"{path}: expected an object")
    missing = REQUIRED_KEYS - node.keys()
    unknown = node.keys() - REQUIRED_KEYS - {"children"}
    if missing or unknown:
        raise TreeError(f"{path}: missing keys {sorted(missing)}, unsupported keys {sorted(unknown)}")
    for key in REQUIRED_KEYS:
        if not isinstance(node[key], str):
            raise TreeError(f"{path}.{key}: expected a string")
    for key in ("groupId", "artifactId", "version", "type"):
        if not TOKEN.fullmatch(node[key]):
            raise TreeError(f"{path}.{key}: invalid value {node[key]!r}")
    if node["classifier"] and not TOKEN.fullmatch(node["classifier"]):
        raise TreeError(f"{path}.classifier: invalid value {node['classifier']!r}")
    if node["optional"] not in ("true", "false"):
        raise TreeError(f"{path}.optional: expected 'true' or 'false'")
    children = node.get("children", [])
    if not isinstance(children, list):
        raise TreeError(f"{path}.children: expected a list")
    identity = tuple(node[key] for key in ("groupId", "artifactId", "version", "type", "classifier"))
    return identity, children


def collect(tree):
    """Return direct dependency identities and libraries keyed by coordinate identity."""
    root, children = _identity(tree, "$")
    if root[:2] != ROOT_COORDINATES or tree["scope"]:
        raise TreeError(f"$: expected unscoped root {':'.join(ROOT_COORDINATES)}, got {coordinate(root)}")
    libraries = {}

    def visit(node, path):
        identity, nested = _identity(node, path)
        if identity == root:
            raise TreeError(f"{path}: dependency on the Java Demo root")
        if node["scope"] not in SCOPES:
            raise TreeError(f"{path}.scope: unsupported scope {node['scope']!r}")
        library = libraries.setdefault(identity, {"scopes": set(), "optional": set(), "dependsOn": set()})
        library["scopes"].add(node["scope"])
        library["optional"].add(node["optional"] == "true")
        for index, child in enumerate(nested):
            child_identity = visit(child, f"{path}.children[{index}]")
            if child_identity == identity:
                raise TreeError(f"{path}.children[{index}]: self-dependency {coordinate(identity)}")
            library["dependsOn"].add(child_identity)
        return identity

    direct = {visit(child, f"$.children[{index}]") for index, child in enumerate(children)}
    names = {}
    for identity in libraries:
        other = names.setdefault(entity_name(identity), identity)
        if other != identity:
            raise TreeError(f"entity name collision: {coordinate(other)} and {coordinate(identity)}")
    return direct, libraries


def library_entity(identity, library):
    scopes = sorted(library["scopes"])
    description = f"Maven library resolved for Java Demo with scope {', '.join(scopes)}."
    if scopes == ["test"]:
        description += " Test-only: not on the runtime classpath."
    tags = ["java", "maven", *(f"maven-scope-{scope}" for scope in scopes)]
    if library["optional"] == {True}:
        tags.append("maven-optional")
    spec = {"type": "library", "lifecycle": "production", "owner": OWNER}
    if library["dependsOn"]:
        spec["dependsOn"] = sorted(entity_ref(child) for child in library["dependsOn"])
    return {
        "apiVersion": "backstage.io/v1alpha1",
        "kind": "Component",
        "metadata": {
            "name": entity_name(identity),
            "title": coordinate(identity),
            "description": description,
            "tags": tags,
            "annotations": {
                "maven.apache.org/coordinates": coordinate(identity),
                "maven.apache.org/scopes": ",".join(scopes),
            },
        },
        "spec": spec,
    }


def render(tree):
    """Render generated file contents for a parsed Maven dependency tree."""
    direct, libraries = collect(tree)
    dependencies = json.dumps(sorted(entity_ref(identity) for identity in direct), indent=2)
    entities = sorted((library_entity(i, lib) for i, lib in libraries.items()), key=lambda e: e["metadata"]["name"])
    documents = "\n---\n".join(json.dumps(entity, indent=2) for entity in entities)
    return {
        DEPENDENCIES_FILE: f"{HEADER}{dependencies}\n",
        LIBRARIES_FILE: f"{HEADER}{documents}\n" if documents else f"{HEADER}# No resolved Maven dependencies.\n",
    }


def resolve_tree(settings):
    with tempfile.TemporaryDirectory() as tmp:
        output = Path(tmp) / "dependency-tree.json"
        command = ["mvn", "-B", "-q", "-f", str(POM)]
        if settings:
            command += ["-s", str(settings)]
        command += [TREE_GOAL, "-DoutputType=json", f"-DoutputFile={output}"]
        subprocess.run(command, check=True)
        return output.read_text(encoding="utf-8")


def sync(files, directory, check):
    """Write files, or return names whose committed content differs when checking."""
    stale = []
    for name, content in files.items():
        path = directory / name
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        stale.append(name)
        if not check:
            path.write_text(content, encoding="utf-8")
    return stale


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale; write nothing")
    parser.add_argument("--settings", type=Path, help="Maven settings.xml passed to mvn -s")
    parser.add_argument("--dependency-tree", type=Path, help="use this dependency:tree JSON instead of running Maven")
    args = parser.parse_args(argv)
    try:
        text = args.dependency_tree.read_text(encoding="utf-8") if args.dependency_tree else resolve_tree(args.settings)
        files = render(json.loads(text))
    except (subprocess.CalledProcessError, json.JSONDecodeError, TreeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    stale = sync(files, DEMO_DIR, args.check)
    if args.check and stale:
        print("stale generated files: " + ", ".join(stale), file=sys.stderr)
        print("run: python3 examples/java-demo/tools/generate_catalog.py", file=sys.stderr)
        return 1
    for name in stale:
        print(f"updated {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
